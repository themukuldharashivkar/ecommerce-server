-- Outbox for order-confirmation emails.
-- A row is inserted in the same transaction that marks the order paid, so the intent to notify
-- is never lost. The unique (order_id, type) constraint means a retried or concurrent payment
-- confirmation can never create a second notification. A background job claims rows and sends them.
CREATE TABLE order_notification (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    type        varchar(40) NOT NULL CONSTRAINT order_notification_type_check
        CHECK (type IN ('ORDER_CONFIRMATION')),
    status      varchar(20) NOT NULL CONSTRAINT order_notification_status_check
        CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')),
    attempts    integer NOT NULL DEFAULT 0,
    last_error  varchar(500),
    created_at  timestamp(6) NOT NULL,
    updated_at  timestamp(6) NOT NULL,
    sent_at     timestamp(6),
    CONSTRAINT uk_order_notification UNIQUE (order_id, type)
);

-- the retry sweeper looks for unsent rows by status and age
CREATE INDEX idx_order_notification_status ON order_notification (status, updated_at)
    WHERE status <> 'SENT';
