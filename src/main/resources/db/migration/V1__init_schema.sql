-- Baseline schema for Bazaarly, matching the JPA entities.
-- Generated from Hibernate's PostgreSQL DDL, then tidied:
--   * IDENTITY entities use identity columns
--   * GenerationType.AUTO entities use sequences with Hibernate's default allocation size (50)
--   * enums are stored as their names (varchar + CHECK) instead of ordinals
-- Indexes on foreign keys and query columns are added in V3.

-- ---------- sequences for GenerationType.AUTO ids ----------
CREATE SEQUENCE address_seq    START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE categories_seq START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE product_seq    START WITH 1 INCREMENT BY 50;
CREATE SEQUENCE review_seq     START WITH 1 INCREMENT BY 50;

-- ---------- users ----------
CREATE TABLE users (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6),
    email       varchar(255),
    first_name  varchar(255),
    last_name   varchar(255),
    mobile      varchar(255),
    password    varchar(255),
    role        varchar(20) CONSTRAINT users_role_check CHECK (role IN ('ROLE_ADMIN', 'ROLE_USER'))
);

CREATE TABLE address (
    id              bigint PRIMARY KEY,
    city            varchar(255),
    first_name      varchar(255),
    last_name       varchar(255),
    mobile          varchar(255),
    state           varchar(255),
    street_address  varchar(255),
    zip_code        varchar(255),
    user_id         bigint REFERENCES users (id)
);

CREATE TABLE payment_information (
    user_id          bigint NOT NULL REFERENCES users (id),
    card_number      varchar(255),
    cardholder_name  varchar(255),
    cvv              varchar(255),
    expiration_date  date
);

-- ---------- catalog ----------
CREATE TABLE categories (
    id                  bigint PRIMARY KEY,
    level               integer NOT NULL,
    name                varchar(50) NOT NULL,
    parent_category_id  bigint REFERENCES categories (id)
);

CREATE TABLE product (
    id                bigint PRIMARY KEY,
    brand             varchar(255),
    color             varchar(255),
    created_at        timestamp(6),
    description       varchar(255),
    discount_persent  integer,
    discounted_price  integer,
    image_url         varchar(255),
    num_ratings       integer,
    price             integer,
    quantity          integer,
    title             varchar(255),
    category_id       bigint REFERENCES categories (id)
);

CREATE TABLE product_sizes (
    product_id  bigint NOT NULL REFERENCES product (id),
    name        varchar(255),
    quantity    integer NOT NULL
);

CREATE TABLE rating (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6),
    rating      double precision,
    product_id  bigint NOT NULL REFERENCES product (id),
    user_id     bigint NOT NULL REFERENCES users (id)
);

CREATE TABLE review (
    id          bigint PRIMARY KEY,
    created_at  timestamp(6),
    review      varchar(255),
    product_id  bigint REFERENCES product (id),
    user_id     bigint REFERENCES users (id)
);

-- ---------- cart ----------
CREATE TABLE cart (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discounte               integer NOT NULL,
    total_discounted_price  integer NOT NULL,
    total_item              integer,
    total_price             double precision,
    user_id                 bigint NOT NULL REFERENCES users (id)
);

CREATE TABLE cart_item (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discounted_price  integer,
    price             integer,
    quantity          integer NOT NULL,
    size              varchar(255),
    user_id           bigint,
    cart_id           bigint REFERENCES cart (id),
    product_id        bigint REFERENCES product (id)
);

-- ---------- orders ----------
CREATE TABLE orders (
    id                                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at                          timestamp(6),
    delivery_date                       timestamp(6),
    discounte                           integer,
    order_date                          timestamp(6),
    order_id                            varchar(255),
    order_status                        varchar(20) CONSTRAINT orders_order_status_check
        CHECK (order_status IN ('PENDING', 'PLACED', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    -- embedded PaymentDetails
    payment_id                          varchar(255),
    payment_method                      varchar(20) CONSTRAINT orders_payment_method_check
        CHECK (payment_method IN ('CREDIT_CARD', 'DEBIT_CARD', 'NET_BANKING', 'UPI', 'PAYPAL', 'GOOGLE_PAY')),
    razorpay_payment_id                 varchar(255),
    razorpay_payment_link_id            varchar(255),
    razorpay_payment_link_reference_id  varchar(255),
    razorpay_payment_link_status        varchar(255),
    status                              varchar(20) CONSTRAINT orders_payment_status_check
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    total_discounted_price              integer,
    total_item                          integer NOT NULL,
    total_price                         double precision NOT NULL,
    shipping_address_id                 bigint REFERENCES address (id),
    user_id                             bigint REFERENCES users (id)
);

CREATE TABLE order_item (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_date     timestamp(6),
    discounted_price  integer,
    price             integer,
    quantity          integer NOT NULL,
    size              varchar(255),
    user_id           bigint,
    order_id          bigint REFERENCES orders (id),
    product_id        bigint REFERENCES product (id)
);
